    dim_list = [(2, 3), (3, 1)]
    for l in range(len(dim_list)):
        in_dim, out_dim = dim_list[l]
        partial_result = [0]*out_dim
        for i in range(in_dim):
            for j in range(out_dim):
                partial_result[j] += eval(f"neuron{l}{i}{j}")(input_x[i])
        input_x = partial_result
